import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import matter from 'gray-matter';
import { unified } from 'unified';
import remarkParse from 'remark-parse';
import remarkGfm from 'remark-gfm';
import remarkRehype from 'remark-rehype';
import rehypeSanitize from 'rehype-sanitize';
import rehypeStringify from 'rehype-stringify';
import prettier from 'prettier';

type FrontMatter = {
  title: string;
  description: string;
  slug: string;
  published: string;
  updated: string;
  category: string;
  affiliateDisclosure?: boolean;
};
const required: (keyof FrontMatter)[] = [
  'title',
  'description',
  'slug',
  'published',
  'updated',
  'category',
];
const root = join(import.meta.dirname, '..');
const contentDirectory = join(root, 'content');
const output = join(root, 'src', 'app', 'content.generated.ts');
const markdownToHtml = (markdown: string) =>
  unified()
    .use(remarkParse)
    .use(remarkGfm)
    .use(remarkRehype)
    .use(rehypeSanitize)
    .use(rehypeStringify)
    .process(markdown);
const articles = [];
for (const file of (await readdir(contentDirectory)).filter(
  (item) => item.endsWith('.md') && item !== 'article-template.md',
)) {
  const parsed = matter(await readFile(join(contentDirectory, file), 'utf8'));
  for (const field of required)
    if (typeof parsed.data[field] !== 'string' || !parsed.data[field])
      throw new Error(`${file}: front matter '${field}' is required.`);
  if (
    !/^\d{4}-\d{2}-\d{2}$/.test(parsed.data.published) ||
    !/^\d{4}-\d{2}-\d{2}$/.test(parsed.data.updated)
  )
    throw new Error(`${file}: published and updated must use YYYY-MM-DD.`);
  const html = String(await markdownToHtml(parsed.content));
  articles.push({
    ...(parsed.data as FrontMatter),
    affiliateDisclosure: parsed.data.affiliateDisclosure === true,
    html,
  });
}
const slugs = articles.map((article) => article.slug);
if (new Set(slugs).size !== slugs.length)
  throw new Error('Article slugs must be unique.');
const source = `// Generated by scripts/generate-content.ts. Do not edit.\nexport interface Article { title: string; description: string; slug: string; published: string; updated: string; category: string; affiliateDisclosure: boolean; html: string; }\nexport const articles: Article[] = ${JSON.stringify(articles, null, 2)} as const;\n`;
await writeFile(
  output,
  await prettier.format(source, {
    parser: 'typescript',
    singleQuote: true,
    trailingComma: 'all',
  }),
);
